const { chromium } = require('playwright');
const out = [];
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-ES' });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push('PAGE ' + e.message));
  p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
  await p.goto('https://stocked-app.github.io/MAXORA/?v=' + Date.now(), { waitUntil: 'load' });
  await p.waitForTimeout(5000);
  await p.screenshot({ path: 'shots/t1.png' });
  out.push('tutorial visibile: ' + await p.evaluate(() => !!document.querySelector('.tu-root:not(.hidden)')));
  await p.click('.tu-next'); await p.click('.tu-link'); await p.click('.tu-next'); await p.click('.tu-next');
  await p.waitForTimeout(1500);
  await p.screenshot({ path: 'shots/t2.png' });
  out.push('fumetto: ' + await p.evaluate(() => document.querySelector('.cm-tip') && document.querySelector('.cm-tip').innerText.replace(/\n/g, ' ')));
  out.push('errori: ' + (errs.join(' | ') || 'nessuno'));
  require('fs').writeFileSync('shots/out.txt', out.join('\n'));
  await b.close();
})().catch((e) => { out.push('ERRORE: ' + e.message); require('fs').writeFileSync('shots/out.txt', out.join('\n')); process.exit(0); });
